// Convention checks for the rules in CLAUDE.md that CI could not previously
// enforce. Run by `pnpm check:conventions`, and in CI after build.
//
// Why this exists: on 2026-08-04 an audit found that every bug in the repo,
// including two that destroyed user data, passed typecheck, lint and build.
// CLAUDE.md is complete and correct, and its rules were still broken
// repeatedly by agents that had read it. A rule that cannot fail the build is
// a suggestion. These are the rules mechanical enough to check.
//
// Known existing violations live in scripts/conventions-baseline.json so this
// can block NEW violations immediately rather than warning forever. The
// baseline is a debt list: it should only ever shrink. A stale entry (one that
// no longer matches anything) also fails, so the file cannot rot.
//
// These are greps with judgement, not a type system. A false positive gets an
// entry in the baseline with a reason, which is more useful documentation than
// the prose rule was.

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { join, dirname, resolve, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BASELINE_PATH = join(ROOT, 'scripts', 'conventions-baseline.json')

const SOURCE_DIRS = ['app', 'components', 'lib', 'hooks', 'stores', 'trigger', 'tests', 'scripts']
const SKIP_DIRS = new Set(['node_modules', '.next', '.git', 'dist', 'build'])

// Generated by `pnpm types:gen`, never hand edited, so not ours to police.
const GENERATED = new Set(['lib/types/database.ts'])

// Tables whose rows render on the schedule day view or the Dates sidebar.
// A server action writing any of these has to revalidate the schedule route,
// because the day view's edit panels deliberately do not refresh client side.
const SCHEDULE_TABLES = [
  'shows', 'day_sheets', 'transport_segments', 'transport_assignments',
  'hotel_stays', 'room_assignments', 'day_events', 'day_items', 'tour_dates',
  'rehearsals', 'people', 'contacts',
  'guest_list_entries', 'guest_list_allotments',
]

// requireUser() is impossible before a session exists. These are the only
// legitimate exceptions, and they are rate limited instead.
const PRE_SESSION_ACTIONS = new Set(['app/(auth)/login/actions.ts'])

const violations = []

function report(rule, file, line, message, key) {
  violations.push({ rule, file, line, message, key: key ?? `${rule}|${file}` })
}

function walk(dir, out = []) {
  if (!existsSync(dir)) return out
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full, out)
    else out.push(full)
  }
  return out
}

const rel = (f) => f.slice(ROOT.length + 1)
const lineOf = (src, index) => src.slice(0, index).split('\n').length

const sourceFiles = SOURCE_DIRS
  .flatMap((d) => walk(join(ROOT, d)))
  .filter((f) => ['.ts', '.tsx', '.mjs'].includes(extname(f)))
  .filter((f) => !GENERATED.has(rel(f)))

// Extracts exported async functions as { name, body, index }. Brace counting,
// which is good enough here: these files are formatted and none of them put a
// stray unmatched brace inside a string literal. If that ever changes this
// check gets noisier, not wrong.
function exportedAsyncFunctions(src) {
  const found = []
  const re = /export\s+async\s+function\s+(\w+)\s*\(/g
  let m
  while ((m = re.exec(src)) !== null) {
    // Find the body's opening brace, not the first brace after the name. Half
    // these actions take an inline object type (`data: { ... }`) or return
    // `Promise<{ ... }>`, so the naive first-brace search lands in the
    // signature and reads the parameter list as the body.
    let p = src.indexOf('(', m.index)
    let parenDepth = 0
    let afterParams = -1
    for (let k = p; k < src.length; k++) {
      if (src[k] === '(') parenDepth++
      else if (src[k] === ')') {
        parenDepth--
        if (parenDepth === 0) { afterParams = k + 1; break }
      }
    }
    if (afterParams === -1) continue

    // Skip a return type annotation, which can itself contain braces.
    let angleDepth = 0
    let i = -1
    for (let k = afterParams; k < src.length; k++) {
      const c = src[k]
      if (c === '<') angleDepth++
      else if (c === '>') angleDepth--
      else if (c === '{' && angleDepth === 0) { i = k; break }
    }
    if (i === -1) continue
    let depth = 0
    let end = i
    for (; end < src.length; end++) {
      if (src[end] === '{') depth++
      else if (src[end] === '}') {
        depth--
        if (depth === 0) break
      }
    }
    found.push({ name: m[1], body: src.slice(i, end + 1), index: m.index })
  }
  return found
}

// ---- Rule 1: requireUser() is the first statement of every server action ----
// Server actions are publicly POSTable endpoints. Validating input, or doing
// anything else, before the auth gate means unauthenticated callers reach that
// logic.
for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  if (!src.includes("'use server'")) continue
  if (PRE_SESSION_ACTIONS.has(rel(file))) continue

  for (const fn of exportedAsyncFunctions(src)) {
    // First non-empty, non-comment line inside the body.
    const first = fn.body
      .split('\n')
      .slice(1)
      .map((l) => l.trim())
      .find((l) => l && !l.startsWith('//') && !l.startsWith('/*') && !l.startsWith('*'))

    if (!first) continue
    if (!/requireUser\s*\(/.test(first)) {
      report(
        'requireUser-first',
        rel(file),
        lineOf(src, fn.index),
        `${fn.name}() does not call requireUser() as its first statement.`,
        `requireUser-first|${rel(file)}|${fn.name}`
      )
    }
  }
}

// ---- Rule 2: actions writing schedule-rendered tables must revalidate ----
// Forgetting this is silent: the panel says "Saved." and the timeline keeps the
// old value. It shipped three separate times before this check existed.
for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  if (!src.includes("'use server'")) continue

  for (const fn of exportedAsyncFunctions(src)) {
    const written = SCHEDULE_TABLES.filter((t) => {
      const re = new RegExp(`from\\(['"\`]${t}['"\`]\\)[\\s\\S]{0,200}?\\.(insert|update|upsert|delete)\\(`)
      return re.test(fn.body)
    })
    if (written.length === 0) continue

    const revalidatesSchedule = /revalidatePath\([^)]*schedule/.test(fn.body)
    if (!revalidatesSchedule) {
      report(
        'revalidate-schedule',
        rel(file),
        lineOf(src, fn.index),
        `${fn.name}() writes ${written.join(', ')} but never revalidates the schedule route.`,
        `revalidate-schedule|${rel(file)}|${fn.name}`
      )
    }
  }
}

// ---- Rule 2b: no .default() on an action-facing validator ----
// The quietest half of the null-versus-undefined rule, and the one that has
// actually destroyed data. Zod's .default() invents a value for a key the form
// never submitted, so a partial form posted to an action that writes the whole
// row does not merely fail to update a column, it writes a value the TM never
// chose. daySheetFormSchema carried .default('none') on catering_type; the
// schedule day view's show panel submits 14 time fields and no catering, so
// every load-in edit set catering to 'none' and nulled six catering columns
// alongside it. Crew silently stopped being told about food.
//
// Scoped to lib/validators/ because that is where every action-facing schema
// lives by convention, and because the same call on a non-schema object is
// unrelated. There is no legitimate exception here that a required field plus
// an explicit fallback at the call site does not express better: a fallback in
// the action is visible in the diff, and a default in the schema is visible to
// nobody. If one ever does turn up, it belongs in the baseline with a reason
// rather than in a weakened rule.
for (const file of sourceFiles.filter((f) => rel(f).startsWith('lib/validators/'))) {
  const src = readFileSync(file, 'utf8')
  const re = /\.default\(/g
  let m
  while ((m = re.exec(src)) !== null) {
    // Skip the prose. Several of these files explain at length why they carry
    // no default, and a check that fires on its own documentation teaches
    // people to delete the documentation.
    const line = src.slice(src.lastIndexOf('\n', m.index) + 1, src.indexOf('\n', m.index))
    if (line.trim().startsWith('//') || line.trim().startsWith('*')) continue

    report(
      'no-schema-default',
      rel(file),
      lineOf(src, m.index),
      '.default() on a validator invents a value for a field the form never sent. ' +
        'Make it required, or optional, and put the fallback at the call site.',
      `no-schema-default|${rel(file)}|${lineOf(src, m.index)}`
    )
  }
}

// ---- Rule 3: never getSession(), always getUser() ----
for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  const i = src.search(/\.getSession\s*\(/)
  if (i !== -1) {
    report('no-getSession', rel(file), lineOf(src, i), 'Uses getSession(). Use getUser().')
  }
}

// ---- Rule 4: every Anthropic call caches its first system block ----
// A call without cache_control pays full token cost on every request and blows
// the per tour cost model.
for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  const i = src.search(/messages\.create\s*\(/)
  if (i !== -1 && !src.includes('cache_control')) {
    report(
      'anthropic-cache-control',
      rel(file),
      lineOf(src, i),
      'Anthropic call with no cache_control on the system block.'
    )
  }
}

// ---- Rule 5: no unguarded .in() with a possibly empty array ----
// An empty .in() is a network round trip that can only ever return nothing.
// Array literals are provably non empty; a bare identifier needs a guard.
for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  const re = /\.in\(\s*['"`][\w.]+['"`]\s*,\s*([A-Za-z_$][\w$.]*)\s*\)/g
  let m
  while ((m = re.exec(src)) !== null) {
    const ident = m[1]
    const base = ident.split('.')[0]
    const guarded =
      new RegExp(`${base}[\\w$.]*\\.length`).test(src) ||
      new RegExp(`${base}[\\w$.]*\\.size`).test(src)
    if (!guarded) {
      report(
        'unguarded-in',
        rel(file),
        lineOf(src, m.index),
        `.in() on '${ident}' with no length guard in this file.`,
        `unguarded-in|${rel(file)}|${ident}`
      )
    }
  }
}

// ---- Rule 6: no em-dashes, anywhere ----
const PROSE_FILES = [
  'CLAUDE.md', 'COMPONENTS.md', '.cursorrules', '.env.example', 'README.md',
  'tests/README.md',
]
const emDashTargets = [
  ...sourceFiles,
  ...walk(join(ROOT, 'supabase', 'migrations')).filter((f) => f.endsWith('.sql')),
  ...PROSE_FILES.map((f) => join(ROOT, f)).filter(existsSync),
  // The workflow files carry real explanatory prose now (the deploy job's comment
  // block is a dozen lines), and nothing was checking them. Added 2026-08-04 on
  // noticing that the file where the two-runtime lesson is written down was
  // outside every check in this script.
  ...walk(join(ROOT, '.github')).filter((f) => f.endsWith('.yml') || f.endsWith('.yaml')),
]
// Built from its code point rather than written as a literal, so this file does
// not trip its own check. Found by running the check on itself, which is the
// kind of thing that argues for the check existing.
const EM_DASH = String.fromCharCode(0x2014)

for (const file of emDashTargets) {
  const src = readFileSync(file, 'utf8')
  const i = src.indexOf(EM_DASH)
  if (i !== -1) {
    report('no-em-dash', rel(file), lineOf(src, i), 'Contains an em-dash.')
  }
}

// ---- Rule 8: a destructive migration states its deploy order ----
// Vercel redeploys on merge. Trigger.dev deploys from its own CI job, and before
// that job existed it deployed by hand or not at all. A migration that drops a
// column therefore has to land after BOTH runtimes are running the code that
// stopped reading it, not after the merge.
//
// This bit on 2026-08-04. Brief 36 step 3 dropped shows.load_in_at and
// shows.curfew_at; Vercel shipped the code that stopped selecting them and
// Trigger.dev did not, so every inbound /itinerary (which runs only on
// Trigger.dev) hit a 42703 and told the crew member the tour had no shows. The
// grep that "proved" no code read those columns had proved it about the repo,
// never about what was running.
//
// The CI deploy job now makes that skew almost impossible, so this check is the
// second layer rather than the first: it cannot verify that both runtimes are
// actually current, only force whoever writes the migration to say they thought
// about it. That is worth having anyway, because the annotation shows up in the
// diff where a reviewer sees it, and because a deploy job can be removed or fail.
const DESTRUCTIVE_SQL = /\b(drop\s+column|drop\s+table)\b/i
const DEPLOY_ORDER_MARKER = /--\s*deploy-order:/i

// Applies to migrations written from 2026-08-05, the day after this rule existed.
// Four migrations before that line drop something without the annotation, and
// they are not baselined, because the baseline is for violations that could be
// fixed and are not yet. These cannot be fixed: all four are already applied to
// production, the deploy they describe is months past for three of them, and
// editing an applied migration file to add a comment is not something to do
// casually (whether the Supabase CLI minds is not verifiable from here, so it is
// not worth finding out for a retroactive comment).
//
// The rule is about a decision taken at the moment a migration is written, so it
// is genuinely meaningless applied backwards. This is a scope, not a weakening:
// every future destructive migration is covered, which is the entire population
// the rule can affect.
const RULE_APPLIES_FROM = '20260805'

for (const file of walk(join(ROOT, 'supabase', 'migrations')).filter((f) => f.endsWith('.sql'))) {
  const timestamp = rel(file).split('/').pop().slice(0, 8)
  if (timestamp < RULE_APPLIES_FROM) continue

  const src = readFileSync(file, 'utf8')
  const m = DESTRUCTIVE_SQL.exec(src)
  if (!m) continue
  if (DEPLOY_ORDER_MARKER.test(src)) continue

  report(
    'destructive-migration-deploy-order',
    rel(file),
    lineOf(src, m.index),
    `Drops a column or table without a "-- deploy-order:" line. Both Vercel and ` +
      `Trigger.dev must already be running the code that stopped reading it. ` +
      `State that in the migration.`,
  )
}

// ---- Rule 7: every env var read is declared in .env.example ----
// And every var reachable from trigger/jobs/ is marked [BOTH], because
// Trigger.dev cannot see Vercel's environment. When that is wrong the job fails
// after the webhook already returned 200, so nothing looks broken.
const envExample = existsSync(join(ROOT, '.env.example'))
  ? readFileSync(join(ROOT, '.env.example'), 'utf8')
  : ''

// [BOTH] usually sits in a trailing comment, but EMAIL_ROOT_DOMAIN is the one
// var that ships with a value, and a trailing comment after a value can end up
// inside the value depending on the parser, so its marker is on the comment
// lines above it. Accept either placement rather than forcing that file into a
// shape it has a documented reason not to take.
const declared = new Map()
let commentBlock = []
for (const rawLine of envExample.split('\n')) {
  if (rawLine.trim().startsWith('#')) {
    commentBlock.push(rawLine)
    continue
  }
  const m = rawLine.match(/^([A-Z0-9_]+)=/)
  if (m) {
    const marked = rawLine.includes('[BOTH]') || commentBlock.some((c) => c.includes('[BOTH]'))
    declared.set(m[1], marked)
  }
  commentBlock = []
}

// Supplied by the runtime (Node, Next, Vercel, GitHub Actions), not config we
// set, so they are not part of the .env.example contract.
const RUNTIME_ENV = new Set(['NODE_ENV', 'CI', 'VERCEL', 'VERCEL_ENV', 'VERCEL_URL', 'PORT'])

function envVarsIn(src) {
  return [...src.matchAll(/process\.env\.([A-Z0-9_]+)/g)]
    .map((m) => m[1])
    .filter((v) => !RUNTIME_ENV.has(v))
}

for (const file of sourceFiles) {
  const src = readFileSync(file, 'utf8')
  for (const v of new Set(envVarsIn(src))) {
    if (!declared.has(v)) {
      report(
        'env-in-example',
        rel(file),
        lineOf(src, src.indexOf(`process.env.${v}`)),
        `${v} is read here but is not in .env.example.`,
        `env-in-example|${rel(file)}|${v}`
      )
    }
  }
}

// Transitive import walk from the job entry points, so a var read three files
// deep in lib/ is still caught.
function resolveImport(spec, fromFile) {
  let base
  if (spec.startsWith('@/')) base = join(ROOT, spec.slice(2))
  else if (spec.startsWith('.')) base = resolve(dirname(fromFile), spec)
  else return null

  for (const cand of [base, `${base}.ts`, `${base}.tsx`, join(base, 'index.ts'), join(base, 'index.tsx')]) {
    if (existsSync(cand) && statSync(cand).isFile()) return cand
  }
  return null
}

const jobReachable = new Set()
const queue = walk(join(ROOT, 'trigger')).filter((f) => ['.ts', '.tsx'].includes(extname(f)))
while (queue.length > 0) {
  const file = queue.pop()
  if (jobReachable.has(file)) continue
  jobReachable.add(file)
  const src = readFileSync(file, 'utf8')
  for (const m of src.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
    const target = resolveImport(m[1], file)
    if (target && !jobReachable.has(target)) queue.push(target)
  }
}

for (const file of jobReachable) {
  const src = readFileSync(file, 'utf8')
  for (const v of new Set(envVarsIn(src))) {
    if (declared.has(v) && declared.get(v) === false) {
      report(
        'env-both-marker',
        rel(file),
        lineOf(src, src.indexOf(`process.env.${v}`)),
        `${v} is reachable from trigger/jobs/ but is not marked [BOTH] in .env.example.`,
        `env-both-marker|${v}`
      )
    }
  }
}

// ---- Rule 9: the dev login route keeps both its guards ----
// app/api/dev/e2e-login/route.ts mints a session from an email. That is exactly
// as dangerous as it sounds, and the only things standing between it and the
// internet are two guards: no E2E_LOGIN_SECRET in the environment means no
// route, and a request that does not present the secret gets nothing.
//
// The secret is set in the CI job and nowhere else, so in production the first
// guard is what makes the endpoint non-existent. Removing it, or "fixing" it to
// a NODE_ENV check because that is what the sibling notify-test route does,
// puts a session-minting endpoint on the live site. A NODE_ENV check is also
// wrong in the other direction: the e2e job serves a production build with
// `next start`, so it would 404 the route in the only place it is meant to work.
//
// Checked as a pair rather than as separate tokens: the condition has to be
// tied to the status code, or a file that merely mentions 404 somewhere passes.
const E2E_LOGIN_ROUTE = join(ROOT, 'app', 'api', 'dev', 'e2e-login', 'route.ts')
if (existsSync(E2E_LOGIN_ROUTE)) {
  const src = readFileSync(E2E_LOGIN_ROUTE, 'utf8')
  const file = rel(E2E_LOGIN_ROUTE)

  const secretGuard = /if\s*\(\s*!\s*secret\s*\)[\s\S]{0,200}?status:\s*404/
  const headerGuard = /headers\.get\(\s*['"]x-e2e-secret['"]\s*\)[\s\S]{0,600}?status:\s*403/

  if (!/process\.env\.E2E_LOGIN_SECRET/.test(src) || !secretGuard.test(src)) {
    report(
      'e2e-login-guards',
      file,
      1,
      'Does not return 404 when E2E_LOGIN_SECRET is absent. That guard is what ' +
        'makes this route non-existent in production.',
      'e2e-login-guards|secret-absent-404'
    )
  }

  if (!headerGuard.test(src)) {
    report(
      'e2e-login-guards',
      file,
      1,
      'Does not compare the x-e2e-secret header and return 403 on a mismatch.',
      'e2e-login-guards|wrong-secret-403'
    )
  }

  if (/process\.env\.NODE_ENV/.test(src)) {
    report(
      'e2e-login-guards',
      file,
      lineOf(src, src.indexOf('process.env.NODE_ENV')),
      'Guards on NODE_ENV. The e2e job serves a production build with `next ' +
        'start`, so this 404s the route in the only place it works. Guard on the ' +
        "secret's presence instead.",
      'e2e-login-guards|node-env'
    )
  }
}

// ---- Rule 10: the day item kind list agrees with the database ----
// Brief 42 replaced twenty day_sheets columns with rows in day_items, and the
// set of kinds a row may hold is stated twice: as a check constraint in the
// migration, and as the array in lib/schedule/day-item-kinds.ts that the combo
// box, the timeline, the comms templates and the parser all read.
//
// Nothing else can catch them disagreeing. Add a kind to the array alone and
// every write of it fails at runtime with a constraint violation, on a TM's day
// view, because tsc cannot see a SQL string. Add it to the constraint alone and
// it is a kind the app can store and cannot label, which renders as a raw
// 'press_call' on the timeline.
//
// The constraint is read from the LAST migration that mentions day_items, not
// from the create-table one, so a future migration that drops and re-adds the
// constraint to add a kind is picked up rather than ignored.
const KIND_LIST_PATH = join(ROOT, 'lib', 'schedule', 'day-item-kinds.ts')
const MIGRATIONS_DIR = join(ROOT, 'supabase', 'migrations')

if (existsSync(KIND_LIST_PATH) && existsSync(MIGRATIONS_DIR)) {
  const kindListSrc = readFileSync(KIND_LIST_PATH, 'utf8')

  // Matches the array entries (kind: 'load_in',) and not the interface field
  // (kind: string), because the latter has no quotes.
  const listKinds = [...kindListSrc.matchAll(/^\s*kind:\s*'([a-z_]+)'/gm)].map((m) => m[1])

  let constraintKinds = null
  let constraintFile = null

  for (const name of readdirSync(MIGRATIONS_DIR).sort()) {
    if (!name.endsWith('.sql')) continue
    const src = readFileSync(join(MIGRATIONS_DIR, name), 'utf8')
    if (!src.includes('day_items')) continue

    // The check constraint body, whether written inline on the column or added
    // later with `add constraint ... check (kind in (...))`.
    const match = [...src.matchAll(/check\s*\(\s*kind\s+in\s*\(([\s\S]*?)\)/g)].pop()
    if (!match) continue

    constraintKinds = [...match[1].matchAll(/'([a-z_]+)'/g)].map((m) => m[1])
    constraintFile = name
  }

  // Both halves have to be non-empty, or a regex that quietly stopped matching
  // would make this rule pass while comparing nothing. Same reasoning as the
  // file-count guard in tests/unit/no-retired-routes.test.ts.
  if (listKinds.length === 0) {
    report(
      'day-item-kinds',
      rel(KIND_LIST_PATH),
      1,
      'Found no kinds in the array. Either the file changed shape or this check ' +
        'is broken; either way it is no longer comparing anything.',
      'day-item-kinds|empty-list'
    )
  } else if (constraintKinds === null) {
    report(
      'day-item-kinds',
      'supabase/migrations',
      1,
      'No migration states a check constraint on day_items.kind, so the kind ' +
        'list is unenforced at the database.',
      'day-item-kinds|no-constraint'
    )
  } else {
    const inListOnly = listKinds.filter((k) => !constraintKinds.includes(k))
    const inDbOnly = constraintKinds.filter((k) => !listKinds.includes(k))

    if (inListOnly.length > 0) {
      report(
        'day-item-kinds',
        rel(KIND_LIST_PATH),
        lineOf(kindListSrc, kindListSrc.indexOf(`kind: '${inListOnly[0]}'`)),
        `${inListOnly.join(', ')} in the kind list but not in the day_items check ` +
          `constraint (${constraintFile}). Writing one would fail on a TM's day view.`,
        'day-item-kinds|list-only'
      )
    }

    if (inDbOnly.length > 0) {
      report(
        'day-item-kinds',
        `supabase/migrations/${constraintFile}`,
        1,
        `${inDbOnly.join(', ')} allowed by the check constraint but missing from ` +
          'the kind list. The app can store it and cannot label it.',
        'day-item-kinds|db-only'
      )
    }
  }
}

// ---- Rule 11: luxon is confined to the calendar localizer ----
// date-fns is not used, and luxon is present for one reason only: react-big-
// calendar's named-timezone support runs through luxonLocalizer, which needs a
// luxon DateTime. That is the whole justification for the dependency, so a luxon
// import anywhere else is a new authority on wall-clock time competing with the
// two the app already has (resolveTourDateId and localDateInZone), and it is
// exactly the class of stray `DateTime.fromJSDate(...).startOf('day')` in a
// server action that would reintroduce the timezone bug this containment exists
// to prevent. RBC's own per-zone support is an unmerged PR open since 2022
// (jquense/react-big-calendar#2293), which is why the containment is a rule
// rather than a temporary workaround: it is not going away.
//
// Allowed in exactly two places: the localizer that owns the RBC integration,
// and the calendar component it is built for. Everywhere else, derive the day
// through lib/schedule/day-link.ts and lib/schedule/datetime.ts instead.
const LUXON_ALLOWED = new Set([
  'lib/schedule/calendar-localizer.ts',
  'components/schedule/day-calendar.tsx',
])
const LUXON_IMPORT = /(?:from\s+['"]luxon['"]|require\(\s*['"]luxon['"]\s*\)|import\s+['"]luxon['"])/
for (const file of sourceFiles) {
  if (LUXON_ALLOWED.has(rel(file))) continue
  const src = readFileSync(file, 'utf8')
  const m = LUXON_IMPORT.exec(src)
  if (m) {
    report(
      'luxon-containment',
      rel(file),
      lineOf(src, m.index),
      'Imports luxon outside the calendar localizer. luxon exists only for ' +
        "react-big-calendar's localizer; derive the day through resolveTourDateId() " +
        'and localDateInZone() instead.',
      `luxon-containment|${rel(file)}`
    )
  }
}

// ---- Rule 12: no document states a number about this repo ----
// A number written into prose is a number that will be wrong within a week,
// because nothing tells you when it moves. On 2026-08-11 the baseline count,
// the three test counts and the migration count were each written down in four
// places, several of them stale. scripts/facts.mjs computes all of them and
// `pnpm facts` prints them, so no document needs to state one.
//
// This checks the baseline count specifically, because it is the one that has
// actually drifted: CLAUDE.md cites it while arguing about the check itself.
//
// An earlier version of this rule also compared a generated block committed
// inside OPERATIONS.md against the computed values. That was removed the same
// day it landed. A committed block is still a number written down, and it went
// stale immediately: a pull request adding one unit test file turned main red
// without touching OPERATIONS.md at all, because the block had been generated
// before that test existed. The lesson is the rule, not an exception to it.
const COUNT_NEAR_BASELINE =
  /(?:stands? at|stood at|is (?:now )?at|is now|sits at|holds|has|down to)\s+(\d+)\b|\b(\d+)\s+(?:known\s+)?(?:baselined?\s+)?(?:entries|violations)\b/gi
const FACT_DOCS = ['CLAUDE.md', 'COMPONENTS.md', 'OPERATIONS.md', 'README.md', 'tests/README.md']
for (const doc of FACT_DOCS) {
  const full = join(ROOT, doc)
  if (!existsSync(full)) continue
  const src = readFileSync(full, 'utf8')
  for (const anchor of src.matchAll(/baseline/gi)) {
    const from = anchor.index
    const window = src.slice(from, from + 320)
    for (const m of window.matchAll(COUNT_NEAR_BASELINE)) {
      const at = from + m.index
      report(
        'facts-in-prose',
        doc,
        lineOf(src, at),
        `States the baseline count in prose ("${'$'}{m[0].trim()}"). A number about this ` +
          'repo goes stale silently and nothing tells you. Run `pnpm facts` instead ' +
          'of writing the figure.',
        `facts-in-prose|${'$'}{doc}|${'$'}{lineOf(src, at)}`
      )
    }
  }
}

// ---- Compare against the baseline ----
const baseline = existsSync(BASELINE_PATH)
  ? JSON.parse(readFileSync(BASELINE_PATH, 'utf8'))
  : { accepted: {} }

const acceptedKeys = new Set(Object.keys(baseline.accepted ?? {}))
const seenKeys = new Set(violations.map((v) => v.key))

const fresh = violations.filter((v) => !acceptedKeys.has(v.key))
const stale = [...acceptedKeys].filter((k) => !seenKeys.has(k))

const byRule = {}
for (const v of fresh) (byRule[v.rule] ??= []).push(v)

if (fresh.length > 0) {
  console.error('\nConvention violations\n')
  for (const [rule, list] of Object.entries(byRule)) {
    console.error(`  ${rule}`)
    for (const v of list) console.error(`    ${v.file}:${v.line}  ${v.message}`)
    console.error('')
  }
}

if (stale.length > 0) {
  console.error('\nStale baseline entries (fixed, so remove them from scripts/conventions-baseline.json)\n')
  for (const k of stale) console.error(`    ${k}`)
  console.error('')
}

const accepted = violations.length - fresh.length
if (fresh.length === 0 && stale.length === 0) {
  console.log(`Conventions OK. ${accepted} known violation(s) still baselined.`)
  process.exit(0)
}

console.error(
  `${fresh.length} new violation(s), ${stale.length} stale baseline entr(ies), ${accepted} baselined.`
)
process.exit(1)
